# 训练集占的比例。剩下的部分作为验证集。
# 训练集用来更新参数，验证集只用来观察，不参与任何参数更新和词表构建。
# 为什么需要验证集：PLAN.md 的 M1-5 要求先在一个小批次上故意过拟合，
# 目标是让训练损失降到接近 0；还要观察未参与更新的文本，才能检查学到的规律能否迁移。
train_ratio = 0.9

# 上下文长度，记为 T，即一条样本的输入 x 包含多少个位置；目标 y 也有 T 个位置。
# 每个位置都要预测原序列中的下一个 ID，所以准备一对 x、y 要用到连续 T + 1 个 ID。
# 真实训练里它常取 256、512 这样的值，本轮取 8 是为了能手算核对。
block_size = 8

# batch（批）是一组放在一起计算的样本，通常是训练集的一小部分，也叫 mini-batch。
# 批大小记为 B，表示一批有多少条样本。B 决定行数，T 决定每行的列数。
# 本轮 B = 4、T = 8，xb 和 yb 各有 4 行 8 列，共 4 * 8 = 32 个预测位置。
# 每行保留自己的上下文；同批的各行共用模型参数，行之间不会因为组批而接上上下文。
# 为什么组批：GPU 可以并行计算多条样本，并将它们的训练信号汇总。B = 1 也能训练；
# 增大 B 通常需要更多显存，训练效果仍需实验比较。
#
# loss（损失）衡量预测与目标的差异。对当前目标，损失越小表示预测越好。
# 在各行等长、所有位置都参与监督的情况下，常用的平均方式是：
#     L_b = (ell[b, 0] + ... + ell[b, T - 1]) / T
#     L_batch = (L_0 + ... + L_{B - 1}) / B
# ell[b, t] 是第 b 行第 t 个位置的损失，L_b 是该行的平均损失。
# 例如 B = 2、T = 3，两行位置损失分别为 [0.3, 0.6, 0.9] 和 [0.9, 1.2, 1.5]：
# 行平均分别为 1.8 / 3 = 0.6、3.6 / 3 = 1.2；整批平均为 (0.6 + 1.2) / 2 = 0.9。
# 梯度描述损失随参数变化的方向和变化率；平均损失的梯度也是各行损失梯度的平均。
# 在每批更新一次、没有梯度累积的训练中，用同一组参数算完这些损失，再反向传播并更新。
# 本文件只准备 ID 列表；上面的损失和参数更新属于后续练习。
batch_size = 4

# 词表外记号。unk 是 unknown 的缩写，用来表示“这个字符不在词表里”。
# 写成尖括号形式，是为了和语料里真正的字符区分开，肉眼一看就知道它不是原文内容。
unk = "<unk>"


