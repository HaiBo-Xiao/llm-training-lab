# TODO 2：填写词表 vocab，这是数据，不是函数。
# 目标：第 0 位放词表外记号 unk，之后按升序排列训练集里所有不同的字符。
#     词表中的下标就是之后编码使用的 ID，未知字符统一使用第 0 项的 ID。
# 参数：
#     train_text：只用于建词表的训练文本。
#     unk：放在词表首位的特殊记号，本轮为 "<unk>"。
# 返回：
#     vocab：记号加去重、排序后的训练字符，每项对应一个不同的 ID。
# 示例 1：
#     输入：train_text = "猫小猫"，unk = "<unk>"（独立的小例子）。
#     输出：vocab = ["<unk>", "小", "猫"]
#     解释：原始字符 ["猫", "小", "猫"] → 去重并排序 ["小", "猫"]
#         → 在开头加入记号 ["<unk>", "小", "猫"]，对应 ID [0, 1, 2]。
#         重复的“猫”只占一个词表位置；原始训练文本保持原顺序。
# 约束：
#     - 本轮实际训练集有 94 个不同字符，加上记号，词表共 95 项。
#     - 只统计 train_text。用全量文本建词表会让验证字符提前影响词表和编号。
#     - 记号固定在第 0 位，其余字符按升序排列。
# 思路：
#     1. 找出训练文本中的不同字符，并固定它们的顺序。
#     2. 把记号放在这些字符前面，组成一个列表。
# 提示：
#     - set(...) 可以去重，sorted(...) 可以排序，列表可以拼接。
vocab: list[str]=['<unk>']+sorted(set(train_text))
print(len(vocab))

