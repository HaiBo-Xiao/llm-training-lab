    "河水很清，能看见石头缝里的小虾。小猫不吃虾，只吃鱼，因为鱼刺少而虾壳硬。"
    "有一天，河水忽然涨起来，木屋前的石阶被淹掉两级。小猫站在门口看了很久，没有下水。"
    "它想起老猫说过的话：水涨的时候不要靠近河心，那里的水会把猫卷走。"
    "于是小猫回到屋里，把门关好，趴在窗台上等水退。"
