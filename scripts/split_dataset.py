# 参数：
#     text：按原顺序排列的全文。
#     train_ratio：分给训练集的长度比例，切分点按乘积向下取整。
# 返回：
#     train_text：切分点之前的字符串；val_text：从切分点开始的字符串。
# 示例 1：
#     输入：text = "小猫吃鱼。"，train_ratio = 0.6（独立的小例子）。
#     输出：train_text = "小猫吃"，val_text = "鱼。"
#     解释：5 * 0.6 = 3，所以在下标 3 之前切开。
#         原文字符： ["小", "猫", "吃", "鱼", "。"]
#         原文下标： [  0,    1,    2,    3,    4 ]
#         训练字符： ["小", "猫", "吃"]
#         验证字符：                   ["鱼", "。"]
#         数组用于观察切分，两个数据槽位实际保存字符串。
# 约束：
#     - 本轮实际 text 有 185 个字符，train_ratio = 0.9。
#       185 * 0.9 = 166.5，向下取整为 166；训练段长 166，验证段长 19。
#     - 保留原顺序。先打乱字符会破坏“前文预测下一个字符”的关系。
#     - 两段拼起来必须原样还原 text；后续样本不能跨越这个训练/验证边界。
