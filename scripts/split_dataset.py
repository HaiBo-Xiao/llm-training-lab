def encode(s: str) -> list[int]:
    """TODO 4：把字符串 s 转换成字符 ID 列表，词表外的字符映射到记号的 ID。

    与上一个练习的 encode 只有一处不同：那时约定输入都在词表内，直接查表即可；
    现在词表来自训练集，验证集必然有查不到的字符，必须给它们一个明确的归宿。

    参数：
        s：任意字符串，可以包含词表外字符。
    返回：
        与 s 等长的 ID 列表。
    示例 1：
        输入：s = "小猫吃鱼"
        输出：[34, 60, 25, 92]
        解释：使用本轮的训练词表，逐个位置对应如下：
            原始字符： ["小", "猫", "吃", "鱼"]
            编码结果： [ 34,   60,   25,   92 ]
            四个字符都在词表内，编码后仍有四项，顺序保持一致。
    示例 2：
        输入：s = "小猫吃沙"
        输出：[34, 60, 25, 0]
        解释：使用同一份训练词表：
            原始字符： ["小", "猫", "吃", "沙"]
            编码结果： [ 34,   60,   25,    0 ]
            “沙”在词表外，保留它的位置并使用记号的 ID 0。编码只转换编号，还没有切样本。
    约束：
        - 1 <= len(s) <= 10^4
        - 返回长度必须等于 len(s)。遇到词表外字符不能跳过：跳过会让长度悄悄变短，
          错误被隐藏，之后按长度对齐输入和目标时查不出原因。
        - 记号的 ID 恒为 0，因为 TODO 2 已把它固定在词表第 0 位。
    思路：
        1. 逐个取出 s 中的字符。
        2. 在词表内就取它的 ID，不在词表内就取记号的 ID。
        3. 按原顺序收集成列表后 return。
    提示：
        - 字典的 get 方法可以在键不存在时返回一个指定的默认值。
    """
    ans=[]
    for ch in s:
        if ch in stoi:
            ans.append(stoi[ch])
        else:
            ans.append(0)
    return ans


